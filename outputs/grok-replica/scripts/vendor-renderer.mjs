// Rebuild static browser assets from exactly pinned, installed npm packages.
import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const packages = [
  ['marked', '18.1.1', 'lib/marked.esm.js', 'marked.js', ['LICENSE']],
  ['dompurify', '3.4.17', 'dist/purify.es.mjs', 'dompurify.js', ['LICENSE', 'LICENSE-MPL']],
  ['katex', '0.19.0', 'dist/katex.mjs', 'katex.js', ['LICENSE']],
];
const provenance = ['# Vendored browser renderers', '', 'Generated by `npm run vendor:renderer`. No target application code is included.', 'Browser bundles use .js because the static server serves that JavaScript MIME type.', 'KaTeX emits native MathML only, so its HTML fonts/styles are not required.', ''];
for (const [name, version, source, output, licenses] of packages) {
  const base = `node_modules/${name}`, destination = `assets/vendor/${name}`;
  const metadata = JSON.parse(await readFile(`${base}/package.json`, 'utf8'));
  if (metadata.version !== version) throw new Error(`Unexpected ${name} version: ${metadata.version}`);
  await mkdir(destination, { recursive: true });
  const bytes = await readFile(`${base}/${source}`);
  await writeFile(`${destination}/${output}`, bytes);
  for (const license of licenses) await copyFile(`${base}/${license}`, `${destination}/${license}`);
  provenance.push(`- ${name}@${version}: https://registry.npmjs.org/${name}/-/${name}-${version}.tgz`, `  Source: ${source}; SHA-256: ${createHash('sha256').update(bytes).digest('hex')}; license: ${metadata.license}.`);
}
provenance.push('', 'Security guidance: https://marked.js.org/using_advanced (sanitize output); https://katex.org/docs/options (trust:false, output:mathml, fresh macros).', 'DOMPurify upstream: https://github.com/cure53/DOMPurify');
await writeFile('assets/vendor/PROVENANCE.md', provenance.join('\n') + '\n');
